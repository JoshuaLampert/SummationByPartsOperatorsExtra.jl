@testsnippet FSBP_Optim begin
    import Optim, ForwardDiff
    using DoubleFloats: Double64
end

@testitem "FSBP with Optim.jl" setup=[FSBP_Optim] begin
    N = 5
    x_min = -1.0
    x_max = 1.0
    source = GlaubitzNordströmÖffner2023()
    for compact in (true, false)
        show(IOContext(devnull, :compact => compact), source)
    end

    for T in (Float32, Float64, Double64)
        nodes = collect(LinRange{T}(x_min, x_max, N))
        options = Optim.Options(g_tol = eps(T), iterations = 10000)
        let basis_functions = [x -> x^i for i in 0:3]
            # Test errors
            @test_throws ArgumentError function_space_operator(basis_functions, nodes,
                                                               source; derivative_order = 2)
            @test_throws ArgumentError function_space_operator(basis_functions, nodes,
                                                               source;
                                                               sparsity_pattern = ones(Bool,
                                                                                       N,
                                                                                       N))
            @test_throws ArgumentError function_space_operator(basis_functions, nodes,
                                                               source; bandwidth = 2)
            @test_throws ArgumentError function_space_operator(basis_functions, nodes,
                                                               source;
                                                               x0 = zeros(3))
            @test_throws ArgumentError function_space_operator(basis_functions, nodes,
                                                               source;
                                                               basis_functions_weights = ones(3))

            D = function_space_operator(basis_functions, nodes, source; options = options,
                                        verbose = true)

            @test eltype(D) == T
            @test grid(D) ≈ nodes
            @test all(isapprox.(D * ones(T, N), zeros(T, N); atol = 1e3 * eps(T)))
            @test D * nodes ≈ ones(T, N)
            @test D * (nodes .^ 2) ≈ 2 * nodes
            @test D * (nodes .^ 3) ≈ 3 * (nodes .^ 2)
            M = mass_matrix(D)
            @test M * D.D + D.D' * M ≈ mass_matrix_boundary(D)
        end

        let basis_functions = [one, identity, exp]
            D = function_space_operator(basis_functions, nodes, source; options = options)

            @test eltype(D) == T
            @test grid(D) ≈ nodes
            @test all(isapprox.(D * ones(T, N), zeros(T, N); atol = 1e4 * eps(T)))
            @test all(isapprox.(D * nodes, ones(T, N); atol = 1e5 * eps(T)))
            @test all(isapprox.(D * exp.(nodes), exp.(nodes); atol = 1e5 * eps(T)))
            M = mass_matrix(D)
            @test M * D.D + D.D' * M ≈ mass_matrix_boundary(D)
        end
    end

    # test non-equidistant nodes generated by `nodes = [0.0, rand(8)..., 1.0]`
    nodes = [0.0, 0.01585580467018155, 0.18010381213204507, 0.270467434432868,
        0.37699483985320303, 0.5600831197666554, 0.5698824835924449, 0.623949064816263,
        0.8574665549914025, 1.0]
    N = length(nodes)
    let basis_functions = [one, identity, exp]
        D = function_space_operator(basis_functions, nodes, source)

        @test grid(D) ≈ nodes
        @test all(isapprox.(D * ones(N), zeros(N); atol = 1e-11))
        @test D * nodes ≈ ones(N)
        @test D * exp.(nodes) ≈ exp.(nodes)
        M = mass_matrix(D)
        @test M * D.D + D.D' * M ≈ mass_matrix_boundary(D)
    end
end

@testitem "FSBP basis function weights with Optim.jl" setup=[FSBP_Optim] begin
    # With 4 equidistant nodes, the basis functions 1, x, x^2, x^3 cannot all be reproduced
    # exactly. Since the weights act on the basis orthonormalized in the given order, a basis
    # function that should be reproduced (almost) exactly has to come first and get a high weight.
    nodes = collect(range(-1.0, 1.0, length = 4))
    source = GlaubitzNordströmÖffner2023()
    options = Optim.Options(g_tol = 1e-16, iterations = 20000)
    error_cubic(D) = maximum(abs, D * nodes .^ 3 - 3 * nodes .^ 2)

    D = function_space_operator([one, identity, x -> x^2, x -> x^3], nodes, source;
                                options)
    @test error_cubic(D) > 0.1
    D_weighted = function_space_operator([x -> x^3, one, identity, x -> x^2], nodes,
                                         source; options,
                                         basis_functions_weights = [1e3, 1.0, 1.0, 1.0])
    @test error_cubic(D_weighted) < 1e-4
end
